import { Language } from '../types';

export const toBengaliNumber = (num: number | string): string => {
  const bengaliDigits = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
  return String(num).replace(/[0-9]/g, (digit) => bengaliDigits[parseInt(digit, 10)]);
};

export const formatCurrency = (amount: number, lang: Language): string => {
  const formatted = Math.abs(amount).toLocaleString('en-IN');
  const symbol = '৳';
  if (lang === 'bn') {
    return `${symbol} ${toBengaliNumber(formatted)}`;
  }
  return `${symbol} ${formatted}`;
};

export const formatDisplayDate = (dateStr: string, lang: Language): string => {
  if (!dateStr) return '';
  const date = new Date(dateStr);
  if (isNaN(date.getTime())) return dateStr;
  
  if (lang === 'bn') {
    const monthsBn = [
      'জানুয়ারি', 'ফেব্রুয়ারি', 'মার্চ', 'এপ্রিল', 'মে', 'জুন',
      'জুলাই', 'আগস্ট', 'সেপ্টেম্বর', 'অক্টোবর', 'নভেম্বর', 'ডিসেম্বর'
    ];
    const day = toBengaliNumber(date.getDate());
    const month = monthsBn[date.getMonth()];
    const year = toBengaliNumber(date.getFullYear());
    return `${day} ${month}, ${year}`;
  }
  
  return date.toLocaleDateString('en-US', { day: 'numeric', month: 'short', year: 'numeric' });
};

export const formatMonthYear = (monthStr: string, lang: Language): string => {
  // monthStr is expected as "YYYY-MM"
  if (!monthStr) return '';
  const [yearStr, monthNumStr] = monthStr.split('-');
  const monthIndex = parseInt(monthNumStr, 10) - 1;
  
  const monthsBn = [
    'জানুয়ারি', 'ফেব্রুয়ারি', 'মার্চ', 'এপ্রিল', 'মে', 'জুন',
    'জুলাই', 'আগস্ট', 'সেপ্টেম্বর', 'অক্টোবর', 'নভেম্বর', 'ডিসেম্বর'
  ];
  const monthsEn = [
    'January', 'February', 'March', 'April', 'May', 'June',
    'July', 'August', 'September', 'October', 'November', 'December'
  ];

  if (lang === 'bn') {
    return `${monthsBn[monthIndex] || monthNumStr} ${toBengaliNumber(yearStr)}`;
  }
  return `${monthsEn[monthIndex] || monthNumStr} ${yearStr}`;
};

